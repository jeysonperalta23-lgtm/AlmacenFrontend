import { expect, test } from '@playwright/test'

test('carrusel de estantes: flechas, extremos y selección en móvil', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/archivo')
  await page.evaluate(async () => {
    const { estructuraMemory, archivosMemory } = await import('/src/services/archiveMemory.ts')
    estructuraMemory.set(Object.fromEntries(Array.from({ length: 12 }, (_, i) => [String(i + 1), []])))
    archivosMemory.set([{ id: 'exp_1', codigo: 'TEST-1', estante: '1', modulo: 'Abastecimiento', nivel: '1', tipo: 'Contratos', anio: '2026', tomo: '', obs: '' }])
  })
  await page.locator('.tabs-archivo button').filter({ hasText: 'Explorar' }).click()
  await page.getByRole('button', { name: 'Mapa de estantes', exact: true }).click()
  const previous = page.getByRole('button', { name: 'Ver estantes anteriores' })
  const next = page.getByRole('button', { name: 'Ver estantes siguientes' })
  const selector = page.getByRole('group', { name: 'Seleccionar estante' })
  await expect(previous).toBeDisabled()
  await expect(next).toBeEnabled()
  await next.click()
  await expect(previous).toBeEnabled()
  expect(await selector.evaluate(el => el.scrollLeft)).toBeGreaterThan(0)
  for (let i = 0; i < 12 && await next.isEnabled(); i++) {
    await next.evaluate(button => button.click())
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  }
  await expect(next).toBeDisabled()
  await selector.getByRole('button', { name: 'Estante 12 0 exp.' }).click()
  await expect(page.locator('.shelf-caption h3')).toHaveText('Estante 12')
  for (let i = 0; i < 12 && await previous.isEnabled(); i++) {
    await previous.evaluate(button => button.click())
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  }
  await expect(previous).toBeDisabled()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(next).toBeEnabled()
  await next.click()
  await expect(previous).toBeEnabled()
  const carousel = await page.locator('.shelf-carousel').boundingBox()
  expect(carousel.x + carousel.width).toBeLessThanOrEqual(390)
})

test('estante visual: niveles, selección, búsqueda, galería sincronizada y móvil', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.route('**/*action=image*', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="120" height="160"><rect width="120" height="160" fill="white"/><text x="10" y="30">Documento</text></svg>' }))
  await page.goto('/archivo')
  await page.evaluate(async () => {
    const { archivosMemory, estructuraMemory } = await import('/src/services/archiveMemory.ts')
    const { writeDemo } = await import('/src/services/digitalizacionMemory.ts')
    const records = Array.from({ length: 35 }, (_, i) => ({ id: `exp_${i}`, codigo: `OAB-${i}`, estante: '1', modulo: 'Abastecimiento', nivel: i === 34 ? '10' : '2', tipo: 'Contratos', anio: '2026', tomo: 'I', obs: 'Observación de prueba' }))
    records.push({ ...records[0], id: 'cont', codigo: 'CON-1', estante: '2', modulo: 'Contabilidad', nivel: '1' })
    archivosMemory.set(records)
    estructuraMemory.set({ '1': ['Abastecimiento'], '2': ['Contabilidad'], '3': [] })
    writeDemo({ version: 1, sessions: [], finished: [], pages: [{ id: 'p1', expedienteId: 'exp_0', session: 's1', fecha: '2026-09-10' }, { id: 'p2', expedienteId: 'exp_0', session: 's1', fecha: '2026-09-10' }] })
  })
  await page.locator('.tabs-archivo button').filter({ hasText: 'Explorar' }).click()
  await page.getByRole('button', { name: 'Mapa de estantes' }).click()
  await expect(page.locator('.shelf-level h4')).toHaveText(['Nivel 2', 'Nivel 10'])
  await expect(page.locator('.shelf-folder')).toHaveCount(35)
  expect(await page.locator('.shelf-row').first().evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true)
  await page.getByRole('button', { name: /^OAB-0 ·/ }).click()
  await expect(page.locator('#shelf-detail-title')).toHaveText('OAB-0')
  await expect(page.locator('.shelf-detail').getByRole('button', { name: 'Digitalizar / vincular celular' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Visualizar las imágenes adjuntas', exact: true }).click()
  await expect(page.locator('.shelf-preview')).toBeFocused()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Ver página 2', exact: true }).click()
  await expect(page.locator('.shelf-preview img')).toHaveAttribute('src', /page=p2/)
  await page.getByRole('button', { name: /^OAB-1 ·/ }).click()
  await expect(page.locator('.shelf-empty-photos')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Visualizar las imágenes adjuntas', exact: true })).toHaveCount(0)
  await expect(page.locator('.shelf-detail').getByRole('button', { name: 'Digitalizar / vincular celular' })).toBeVisible()
  await page.getByRole('button', { name: /^OAB-0 ·/ }).click()
  await expect(page.locator('.shelf-preview img')).toHaveAttribute('src', /page=p1/)
  await page.evaluate(async () => {
    const { readDemo, writeDemo } = await import('/src/services/digitalizacionMemory.ts')
    const data = readDemo()
    data.pages.push({ id: 'p3', expedienteId: 'exp_0', session: 's1', fecha: '2026-09-10' })
    writeDemo(data)
  })
  await expect(page.getByRole('button', { name: 'Ver página 3' })).toBeVisible()
  await page.getByRole('searchbox', { name: 'Buscar expediente', exact: true }).fill('CON-1')
  await expect(page.locator('.shelf-results')).toContainText('Sin coincidencias')
  await page.getByRole('button', { name: 'Estante 2 1 coincidencias' }).click()
  await expect(page.locator('.shelf-folder')).toHaveCount(1)
  await expect(page.locator('#shelf-detail-title')).toHaveText('Abre una carpeta')
  await page.locator('.shelf-folder').focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('#shelf-detail-title')).toHaveText('CON-1')
  await page.getByRole('button', { name: 'Estante 3 0 coincidencias' }).click()
  await expect(page.locator('.shelf-empty')).toContainText('Este estante está vacío')
  await page.getByRole('searchbox', { name: 'Buscar expediente', exact: true }).fill('')
  await page.getByRole('button', { name: 'Estante 1 35 exp.' }).click()
  await page.getByRole('button', { name: /^OAB-0 ·/ }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  const visual = await page.locator('.shelf-visual').boundingBox()
  const panel = await page.locator('.shelf-detail').boundingBox()
  expect(panel.y).toBeGreaterThan(visual.y + visual.height)
  const map = await page.locator('.shelf-map').boundingBox()
  expect(map.x + map.width).toBeLessThanOrEqual(390)
  expect(await page.locator('.shelf-map').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  expect(errors).toEqual([])
})
