import { expect, test } from '@playwright/test'

test('configuración: crear estantes, gestionar módulos y reiniciarlos al recargar', async ({ page }) => {
  await page.goto('/archivo')
  await page.evaluate(async () => {
    const { estructuraMemory, archivosMemory } = await import('/src/services/archiveMemory.ts')
    estructuraMemory.set({ '1': ['Abastecimiento'], '2': ['Contabilidad'], '3': [] })
    archivosMemory.set([{ id: 'exp_test', codigo: 'OAB-1', estante: '1', modulo: 'Abastecimiento', nivel: '1', tipo: 'Contratos', anio: '2026', tomo: '', obs: '' }])
  })
  await page.getByRole('button', { name: 'Configuración', exact: true }).click()
  const modal = page.getByRole('dialog', { name: /Configurar Estantes y Módulos/ })
  await expect(modal).toBeVisible()
  await modal.getByRole('button', { name: 'Agregar nuevo estante' }).click()
  const estante = modal.getByRole('region', { name: 'Estante 4', exact: true })
  await expect(estante).toBeVisible()
  const input = estante.getByRole('textbox', { name: 'Nuevo módulo para Estante 4' })
  await input.fill('  Tesorería  ')
  await input.press('Enter')
  await expect(estante.getByText('Tesorería', { exact: true })).toBeVisible()
  await input.fill('Tesorería')
  await estante.getByRole('button', { name: 'Agregar', exact: true }).click()
  await expect(estante.getByText('Tesorería', { exact: true })).toHaveCount(1)
  await input.fill('Temporal')
  await input.press('Enter')
  await estante.getByRole('button', { name: 'Quitar Temporal de Estante 4' }).click()
  await expect(estante.getByText('Temporal', { exact: true })).toHaveCount(0)
  await modal.getByRole('button', { name: 'Agregar nuevo estante' }).click()
  await expect(modal.getByRole('region', { name: 'Estante 5', exact: true })).toBeVisible()
  await modal.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await page.locator('.tabs-archivo button').filter({ hasText: 'Registrar' }).click()
  const shelfSelect = page.locator('select').filter({ has: page.locator('option[value="4"]') })
  await shelfSelect.selectOption('4')
  await expect(page.locator('select option[value="Tesorería"]')).toHaveCount(1)
  await page.locator('.tabs-archivo button').filter({ hasText: 'Explorar' }).click()
  await page.getByRole('button', { name: 'Mapa de estantes', exact: true }).click()
  await page.getByRole('button', { name: 'Estante 4 0 exp.' }).click()
  await expect(page.locator('.shelf-empty')).toBeVisible()
  await expect(page.locator('.shelf-legend')).toContainText('Tesorería')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Configuración', exact: true }).click()
  await expect(modal.getByRole('region', { name: 'Estante 4', exact: true })).toContainText('Tesorería')
  await page.keyboard.press('Escape')
  await expect(modal).toBeHidden()
  const menu = await page.locator('.tabs-archivo').boundingBox()
  expect(menu.x).toBeGreaterThanOrEqual(0)
  expect(menu.x + menu.width).toBeLessThanOrEqual(390)
  await page.reload()
  await page.getByRole('button', { name: 'Configuración', exact: true }).click()
  await expect(modal.getByRole('region', { name: 'Estante 4', exact: true })).toHaveCount(0)
  await expect(modal.getByRole('region', { name: 'Estante 1', exact: true })).toContainText('Secretaría')
})
