import { expect, test } from '@playwright/test'

test('registro continuo: aviso temporal, contador en memoria y revisión voluntaria', async ({ page }) => {
  await page.addInitScript(() => {
    for (const name of ['localStorage', 'sessionStorage']) {
      Object.defineProperty(window, name, { get() { throw new Error(`Acceso inesperado a ${name}`) } })
    }
  })
  await page.clock.install()
  await page.goto('/archivo')
  const registrar = page.locator('.tabs-archivo button').filter({ hasText: 'Registrar' })
  const explorar = page.locator('.tabs-archivo button').filter({ hasText: 'Explorar' })
  const badge = explorar.locator('.et-pending-badge')
  const form = page.locator('.fexp-card form')
  const toast = page.locator('.et-registration-toast')
  await registrar.click()
  await form.locator('button[type="submit"]').click()
  await expect(badge).toHaveCount(0)
  await expect(toast).toHaveCount(0)
  async function register(tipo) {
    await form.getByPlaceholder('Ej. 3', { exact: true }).fill('1')
    await form.getByPlaceholder('Ej. Informes').fill(tipo)
    await form.locator('input[type="number"]').fill('2021')
    await form.getByPlaceholder('Ej. II (opcional)').fill('II')
    await form.locator('button[type="submit"]').click()
    await expect(registrar).toHaveAttribute('aria-current', 'page')
    await expect(form.getByPlaceholder('Ej. Informes')).toHaveValue('')
    await expect(form.getByPlaceholder('Ej. 3', { exact: true })).toHaveValue('')
    await expect(form.locator('input[type="number"]')).toHaveValue('')
    await expect(form.getByPlaceholder('Ej. II (opcional)')).toHaveValue('')
    await expect(form.getByRole('status')).toContainText('Expediente guardado correctamente')
    await expect(toast).toContainText('¡Expediente registrado con éxito!')
  }
  await register('Informes')
  await expect(badge).toHaveText('1')
  await page.clock.fastForward(3000)
  await register('Contratos')
  await expect(badge).toHaveText('2')
  await page.clock.fastForward(3000)
  await expect(toast).toBeVisible()
  await page.clock.fastForward(2100)
  await expect(toast).toHaveCount(0)
  await expect(registrar).toHaveAttribute('aria-current', 'page')
  await expect(badge).toHaveText('2')
  await page.locator('.tabs-archivo button').filter({ hasText: 'Inicio' }).click()
  await expect(badge).toHaveText('2')
  await explorar.click()
  await expect(badge).toHaveCount(0)
  const first = page.locator('.et-table tbody tr').first()
  await expect(first).toContainText('Contratos')
  await expect(first.locator('.et-new-badge')).toHaveText('Pendiente de revisar')
  await expect(first).toHaveClass(/is-new/)
  await expect(page.getByRole('region', { name: 'Último expediente registrado' })).toContainText('Contratos')
  await page.clock.fastForward(60000)
  await expect(page.locator('.et-new-badge')).toHaveCount(2)
  await registrar.click()
  await explorar.click()
  await expect(page.locator('.et-new-badge')).toHaveCount(2)
  await first.getByRole('checkbox').check()
  await expect(first.locator('.et-new-badge')).toHaveCount(0)
  await expect(page.locator('.et-new-badge')).toHaveCount(1)
  await page.locator('.et-table tbody tr').nth(1).getByRole('button', { name: /Descartar aviso/ }).click()
  await expect(page.locator('.et-new-badge')).toHaveCount(0)
  await expect(page.locator('.et-table tbody tr').nth(1).getByRole('checkbox')).not.toBeChecked()
  await registrar.click()
  await explorar.click()
  await expect(page.locator('.et-new-badge')).toHaveCount(0)
  await page.getByRole('button', { name: 'Mapa de estantes', exact: true }).click()
  await registrar.click()
  await register('Memorandos')
  await expect(badge).toHaveText('1')
  await toast.getByRole('button', { name: 'Ir a imprimir QR' }).click()
  await expect(explorar).toHaveAttribute('aria-current', 'page')
  await expect(page.getByRole('heading', { name: 'Etiquetas QR', exact: true })).toBeVisible()
  await expect(first).toContainText('Memorandos')
  await expect(first.locator('.et-new-badge')).toHaveText('Pendiente de revisar')
  await expect(badge).toHaveCount(0)
  await expect(toast).toHaveCount(0)
  await page.getByRole('button', { name: 'Ver último expediente', exact: true }).click()
  await expect(page.locator('.et-detail-modal')).toBeVisible()
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await expect(first.locator('.et-new-badge')).toHaveCount(0)
  await expect(first).not.toHaveClass(/is-new/)
  await page.reload()
  await expect(badge).toHaveCount(0)
  await explorar.click()
  await expect(page.locator('.et-new-badge')).toHaveCount(0)
  expect(await page.evaluate(async () => (await import('/src/services/archiveMemory.ts')).archivosMemory.get())).toEqual([])
})
