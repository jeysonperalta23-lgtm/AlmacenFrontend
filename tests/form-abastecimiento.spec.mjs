import { expect, test } from '@playwright/test'

test('Abastecimiento: campos por área, folios opcionales y datos en memoria', async ({ page }) => {
  await page.goto('/archivo')
  await page.locator('.tabs-archivo button').filter({ hasText: 'Registrar' }).click()
  const form = page.locator('.fexp-card form')
  await expect(page.getByLabel('Entidad / Institución')).toHaveCount(0)
  const area = page.getByRole('combobox', { name: 'Área / Unidad' })
  await expect(area).toHaveValue('Subgerencia de Abastecimiento')
  await area.selectOption('')
  expect(await area.evaluate(select => select.validity.valueMissing)).toBe(true)
  await area.selectOption('Abastecimiento')
  await expect(area).toHaveValue('Abastecimiento')
  await area.selectOption('Subgerencia de Abastecimiento')
  await form.locator('select').nth(1).selectOption('Secretaría')
  await expect(area).toHaveCount(0)
  await expect(page.getByLabel('Entidad / Institución')).toHaveCount(0)
  await form.locator('select').nth(1).selectOption('Abastecimiento')
  async function fillBase() {
    await form.getByPlaceholder('Ej. 3', { exact: true }).fill('1')
    await form.getByPlaceholder('Ej. Informes').fill('Informes')
    await form.locator('input[type="number"]').fill('2021')
    await form.getByPlaceholder('Ej. II (opcional)').fill('II')
  }
  const submit = form.locator('button[type="submit"]')
  await fillBase()
  await submit.click()
  await expect.poll(() => page.evaluate(async () => (await import('/src/services/archiveMemory.ts')).archivosMemory.get().length)).toBe(1)
  await fillBase()
  await page.getByLabel('Folio inicial').fill('523')
  await page.getByLabel('Folio final').fill('001')
  await submit.click()
  await expect(form.getByRole('alert')).toContainText('Indica ambos extremos')
  await page.getByLabel('Folio inicial').fill('001')
  await page.getByLabel('Folio final').fill('523')
  await submit.click()
  await expect.poll(() => page.evaluate(async () => (await import('/src/services/archiveMemory.ts')).archivosMemory.get().length)).toBe(2)
  const records = await page.evaluate(async () => [...(await import('/src/services/archiveMemory.ts')).archivosMemory.get()].reverse())
  expect(records[0].folioDesde).toBeUndefined()
  expect(records[1]).toMatchObject({ entidad: 'Municipalidad de Pampas de Hospital', area: 'Subgerencia de Abastecimiento', jurisdiccion: 'Tumbes', tipo: 'Informes', anio: '2021', tomo: 'II', folioDesde: '001', folioHasta: '523' })
  const search = page.getByRole('textbox', { name: 'Buscar o escanear expediente' })
  await search.fill(`ALMACEN:EXP:${records[1].id}`)
  await search.press('Enter')
  await expect(page.locator('.et-detail-grid')).toContainText('001 al 523')
  await page.getByRole('dialog').getByRole('button', { name: 'Editar', exact: true }).click()
  await expect(page.getByLabel('Folio inicial')).toHaveValue('001')
  await expect(area).toHaveValue('Subgerencia de Abastecimiento')
  await area.selectOption('Abastecimiento')
  await form.getByPlaceholder('Ej. 3', { exact: true }).fill('2')
  await submit.click()
  await expect.poll(() => page.evaluate(async () => (await import('/src/services/archiveMemory.ts')).archivosMemory.get()[0].historialUbicacion.length)).toBe(2)
  await search.fill(`ALMACEN:EXP:${records[1].id}`)
  await search.press('Enter')
  const history = page.getByRole('region', { name: 'Historial de ubicación' })
  await expect(history).toContainText('Desde: Estante 1 · Abastecimiento · Nivel 1')
  await expect(history).toContainText('Hasta: Estante 1 · Abastecimiento · Nivel 2')
  await page.getByRole('dialog').getByRole('button', { name: 'Editar', exact: true }).click()
  await expect(area).toHaveValue('Abastecimiento')
  await submit.click()
  const updated = await page.evaluate(async () => (await import('/src/services/archiveMemory.ts')).archivosMemory.get()[0])
  expect(updated.historialUbicacion).toHaveLength(2)
  await page.reload()
  expect(await page.evaluate(async () => (await import('/src/services/archiveMemory.ts')).archivosMemory.get())).toEqual([])
})
